/**
 * Liikekirjaston siemendata (SPEC §6.1): yleiset saliliikkeet suomeksi,
 * kullakin lihasryhmät, väline, tyyppi, hakualiakset ja järkevät oletukset.
 *
 * Oletusten periaatteet:
 * - Painonlisäys: moninivelliikkeet tangolla 2,5 kg, käsipaino- ja eristävät
 *   liikkeet 1,25 kg. Laitteissa 2,5 kg (levypakan askel).
 * - Lepo: isot moninivelet 180 s, kevyemmät moninivelet 150 s, eristävät 90 s.
 * - `kind: 'bodyweight'` = kirjattu paino on lisäpaino, avustetuissa liikkeissä
 *   negatiivinen (SPEC §5).
 * - `kind: 'time'` = sarja kirjataan kestona, joten toistoalue on 1–1.
 * - `aliases` = hakusanat (englanninkieliset nimet ja salislangi). Niitä ei
 *   näytetä nimenä, vain haussa perusteluna ("myös: pec deck").
 * - `since` = kirjastoversio, jossa liike tuli mukaan. `syncExerciseLibrary()`
 *   lisää olemassa olevaan asennukseen vain uudemmat rivit.
 */
